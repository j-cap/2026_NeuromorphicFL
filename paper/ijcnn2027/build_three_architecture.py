def file_hash(path):
    data = path.read_bytes()
    if path.suffix.lower() in {".py", ".csv", ".json", ".md", ".txt", ".tex", ".bib"}:
        data = data.replace(b"\r\n", b"\n")
    return hashlib.sha256(data).hexdigest()


def check_freeze():
    previous = old.check_freeze()
    freeze = json.loads(FREEZE.read_text(encoding="utf-8"))
    assert freeze["status"] == "closed_three_architecture_panel"
    for name, digest in freeze["files"].items():
        if file_hash(REPO / name) != digest:
            raise AssertionError(f"Frozen MLP input changed: {name}")
    return len(previous["files"]), len(freeze["files"])


def paired(a, b, log=False):
    assert len(a) == len(b) and 2 <= len(a) <= 10
    values = np.log(np.array(a) / np.array(b)) if log else np.array(a) - np.array(b)
    estimate = float(values.mean())
    half = T95[len(values)] * float(values.std(ddof=1)) / np.sqrt(len(values))
    return tuple(float(np.exp(x)) if log else x for x in (estimate, estimate-half, estimate+half))


def load_panel(panel):
    if panel != "fmnist_mlp":
        return old.load_panel(panel)
    raw_runs = old.read(MLP / "confirmation_runs.csv")
    raw_history = old.read(MLP / "confirmation_history.csv")
    assert len(raw_runs) == 50 and len(raw_history) == 1550
    runs, curves, hits = {}, {}, {}
    selection = json.loads((MLP / "frozen_selection.json").read_text())
    freeze = json.loads(FREEZE.read_text())
    for method in METHODS:
        rows = sorted([r for r in raw_runs if r["method"] == method], key=lambda r: int(r["partition_seed"]))
        assert [int(r["partition_seed"]) for r in rows] == list(range(11100, 12100, 100))
        assert all(int(r["rounds"]) == 1500 and r["variant"] == old.VARIANTS[method] for r in rows)
        assert all(r["contract_sha256"] == freeze["mlp_contract_sha256"] and
                   r["selection_sha256"] == freeze["mlp_selection_sha256"] and
                   r["point_id"] == selection["selected"][method][0] for r in rows)
        runs[method], curves[method] = rows, []
        for row in rows:
            seed = int(row["partition_seed"])
            assert int(row["train_seed"]) == seed + 90000
            assert int(row["uplink_bits"]) + int(row["unicast_downlink_bits"]) == int(row["unicast_total_bits"])
            curve = sorted([r for r in raw_history if r["method"] == method and int(r["partition_seed"]) == seed], key=lambda r: int(r["round"]))
            assert [int(r["round"]) for r in curve] == [1] + list(range(50, 1501, 50))
            assert curve[-1]["model_sha256"] == row["model_sha256"]
            assert np.all(np.diff([int(r["unicast_total_bits"]) for r in curve]) >= 0)
            curves[method].append(curve)
            for target in (.80, .85, .87):
                hits[method, seed, target] = next((r for r in curve if float(r["test_accuracy"]) >= target), None)
    return runs, curves, hits


def tables(endpoints, targets):
    result = [r"% Generated by build_three_architecture.py; do not edit.",
        r"\begin{table*}[t]\centering\coreColor\footnotesize",
        r"\caption{\mlpRev{Frozen five-method endpoints: CIFAR-10 compact CNN and ResNet-14 at 1,800 rounds; Fashion-MNIST MLP at 1,500. Accuracy and unregularized test CE are mean $\pm$ sample SD over ten paired seeds. Traffic is mean Gbit ($10^9$ bits), including recipient copies. Settings are calibrated separately for each dataset/model.}}",
        r"\label{tab:calibrated-core}", r"\setlength{\tabcolsep}{4.5pt}",
        r"\begin{tabular}{llrrrrr}\toprule",
        r"Model & Method & Accuracy [\%] & Test CE & Upload & Sync./ctrl. & Total \\\midrule"]
    for panel, (title, _, _, _) in PANELS.items():
        rows = [x for x in endpoints if x["panel"] == panel]
        best_acc = max(x["final_test_accuracy_mean"] for x in rows)
        best_ce = min(x["final_test_ce_mean"] for x in rows)
        for j, row in enumerate(rows):
            acc = f"{100*row['final_test_accuracy_mean']:.2f}\\pm{100*row['final_test_accuracy_std']:.2f}"
            ce = f"{row['final_test_ce_mean']:.3f}\\pm{row['final_test_ce_std']:.3f}"
            if row["final_test_accuracy_mean"] == best_acc:
                acc = r"\mathbf{"+acc+"}"
            if row["final_test_ce_mean"] == best_ce:
                ce = r"\mathbf{"+ce+"}"
            total = f"{row['unicast_total_bits_mean']/1e9:.3f}"
            if row["method"] == "event":
                total = r"\mathbf{"+total+"}"
            # Color each cell, since a color declaration in the first cell
            # cannot span the TeX alignment's cell groups.
            values = [title if j == 0 else "", old.TEX[row["method"]], f"${acc}$", f"${ce}$",
                      f"{row['uplink_bits_mean']/1e9:.3f}", f"{row['unicast_downlink_bits_mean']/1e9:.3f}", f"${total}$"]
            if panel == "fmnist_mlp":
                values = [r"\mlpRev{"+x+"}" for x in values]
            result.append(" & ".join(values)+r" \\")
        result.append(r"\midrule")
    result[-1] = r"\bottomrule"
    result += [r"\end{tabular}",
        r"\par\smallskip\parbox{.97\textwidth}{\footnotesize\mlpRev{Bold marks the best mean accuracy, CE and total cost within a panel, without implying statistical superiority. Sync./ctrl. includes initialization and requests. STC retains all coordinates ($p=1$) with ternarization and both residuals; gains are 2/4/2. EF-TopK retention is 5\%/1\%/10\% for compact CNN/ResNet/MLP.}}", r"\end{table*}"]
    target = [r"% Generated by build_three_architecture.py; do not edit.",
        r"\begin{table}[t]\centering\coreColor\footnotesize",
        r"\caption{\mlpRev{Event's unicast saving to the middle declared target: 50\% for CIFAR-10 and 85\% for Fashion-MNIST. All methods reach these targets in 10/10 runs. Descriptive 95\% intervals use paired log cost ratios. Negative savings mean more traffic for Event.}}",
        r"\label{tab:calibrated-targets}", r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular}{llr}\toprule", r"Model & Reference & Saving [\%] (95\% CI) \\\midrule"]
    for panel, (title, _, _, levels) in PANELS.items():
        rows = [x for x in targets if x["panel"] == panel and x["target_percent"] == levels[1]]
        assert len(rows) == 4 and all(x["common_hits"] == 10 for x in rows)
        for j, row in enumerate(rows):
            values = [title if j == 0 else "", old.TEX[row["reference"]],
                      f"{row['saving_percent']:.1f} [{row['saving_ci95_low']:.1f}, {row['saving_ci95_high']:.1f}]"]
            if panel == "fmnist_mlp":
                values = [r"\mlpRev{"+x+"}" for x in values]
            target.append(" & ".join(values)+r" \\")
        target.append(r"\midrule")
    target[-1] = r"\bottomrule"
    target += [r"\end{tabular}", r"\end{table}"]
    return {"generated/three_architecture_results.tex": ("\n".join(result)+"\n").encode(),
            "generated/three_architecture_targets.tex": ("\n".join(target)+"\n").encode()}


def products():
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 7,
        "axes.labelsize": 7, "axes.titlesize": 8, "pdf.fonttype": 42,
        "ps.fonttype": 42, "axes.spines.top": False, "axes.spines.right": False})
    trajectories, axes = plt.subplots(1, 3, figsize=(7.08, 2.65))
    ratios, ratio_axes = plt.subplots(1, 3, figsize=(7.08, 2.65), sharey=True)
    endpoints, effects, target_rows, histories, coverage = [], [], [], [], []
    for ax, ratio_ax, (panel, (title, dataset, horizon, levels)) in zip(axes, ratio_axes, PANELS.items()):
        runs, curves, hits = load_panel(panel)
        for method in METHODS:
            rows = runs[method]
            endpoint = dict(panel=panel, method=method, rounds=horizon, n=10)
            for metric in ("final_test_accuracy", "final_test_ce", "uplink_bits", "unicast_downlink_bits", "unicast_total_bits", "broadcast_total_bits"):
                values = np.array([float(r[metric]) for r in rows])
                endpoint[metric+"_mean"] = float(values.mean())
                endpoint[metric+"_std"] = float(values.std(ddof=1))
            endpoints.append(endpoint)
            x = np.array([[float(r["unicast_total_bits"])/1e9 for r in c] for c in curves[method]])
            y = np.array([[100*float(r["test_accuracy"]) for r in c] for c in curves[method]])
            ax.plot(x.mean(axis=0), y.mean(axis=0), color=old.COLORS[method], ls=old.STYLES[method],
                    lw=1.8 if method == "event" else 1.0, marker=old.MARKERS[method], markevery=5,
                    ms=4.5 if method == "event" else 2.6, zorder=6 if method == "event" else 3)
            ax.fill_between(x.mean(axis=0), y.mean(axis=0)-y.std(axis=0, ddof=1),
                            y.mean(axis=0)+y.std(axis=0, ddof=1), color=old.COLORS[method], alpha=.08)
            for j, r in enumerate(curves[method][0]):
                histories.append(dict(panel=panel, method=method, round=int(r["round"]),
                    mean_unicast_Gbit=float(x[:, j].mean()), mean_test_accuracy_percent=float(y[:, j].mean()),
                    sd_test_accuracy_percent=float(y[:, j].std(ddof=1))))
            for level in levels:
                target = level / 100
                reached = [hits[method, int(r["partition_seed"]), target] for r in rows]
                coverage.append(dict(panel=panel, method=method, target_percent=level,
                    reached=sum(r is not None for r in reached), n_total=10,
                    final_at_or_above=sum(float(r["final_test_accuracy"]) >= target for r in rows),
                    missed_seeds=";".join(str(r["partition_seed"]) for r, h in zip(rows, reached) if h is None)))
            if method == "event":
                continue
            for metric, source, scale, log in (("accuracy_difference_pp", "final_test_accuracy", 100, False),
                    ("ce_difference", "final_test_ce", 1, False), ("unicast_ratio", "unicast_total_bits", 1, True)):
                a, b = [scale*float(r[source]) for r in runs["event"]], [scale*float(r[source]) for r in rows]
                estimate, low, high = paired(a, b, log)
                effects.append(dict(panel=panel, reference=method, metric=metric, n=10, estimate=estimate,
                    ci95_low=low, ci95_high=high, paired_cost_wins=sum(v < w for v, w in zip(a, b)) if log else ""))
            for ti, level in enumerate(levels):
                target = level/100
                pairs = [(hits["event", int(r["partition_seed"]), target], hits[method, int(r["partition_seed"]), target]) for r in rows]
                common = [(a, b) for a, b in pairs if a is not None and b is not None]
                estimate, low, high = paired([float(a["unicast_total_bits"]) for a, b in common],
                                             [float(b["unicast_total_bits"]) for a, b in common], True)
                target_rows.append(dict(panel=panel, reference=method, target_percent=level,
                    event_reached=sum(a is not None for a, b in pairs), reference_reached=sum(b is not None for a, b in pairs),
                    common_hits=len(common), cost_wins=sum(float(a["unicast_total_bits"]) < float(b["unicast_total_bits"]) for a, b in common),
                    ratio=estimate, ratio_ci95_low=low, ratio_ci95_high=high,
                    saving_percent=100*(1-estimate), saving_ci95_low=100*(1-high), saving_ci95_high=100*(1-low),
                    earlier=sum(int(a["round"]) < int(b["round"]) for a, b in common),
                    same=sum(int(a["round"]) == int(b["round"]) for a, b in common),
                    later=sum(int(a["round"]) > int(b["round"]) for a, b in common)))
                ratio_ax.errorbar(list(METHODS[1:]).index(method)+(ti-1)*.2, estimate,
                    yerr=[[estimate-low], [high-estimate]], marker=("o", "s", "^")[ti],
                    ms=3.5, capsize=2, color=("#0072B2", "#D55E00", "#009E73")[ti], lw=1)
        title = f"{title}\n{dataset}"
        ax.set(title=title, xlabel="Total unicast [Gbit]", xscale="log",
               ylim=(9, 62) if panel == "compact_cnn" else (9, 81) if panel == "resnet14" else (9, 91))
        ax.grid(alpha=.2)
        ratio_ax.set(title=title, yscale="log", ylim=(.006, 1.7))
        ratio_ax.set_xticks(range(4), [SHORT[m] for m in METHODS[1:]], rotation=20, ha="right")
        ratio_ax.axhline(1, ls="--", color=".35", lw=.8)
        ratio_ax.grid(axis="y", alpha=.2)
        ratio_ax.legend(handles=[Line2D([], [], color=c, marker=m, ms=3, label=f"{t}%")
            for t, c, m in zip(levels, ("#0072B2", "#D55E00", "#009E73"), ("o", "s", "^"))],
            loc="lower center", bbox_to_anchor=(.5, 1.20), ncol=3, frameon=False,
            fontsize=6.2, handlelength=1.0, columnspacing=.7, handletextpad=.3)
    axes[0].set_ylabel("Test accuracy [%]")
    ratio_axes[0].set_ylabel("Event / reference traffic")
    trajectories.legend(handles=[Line2D([], [], color=old.COLORS[m], ls=old.STYLES[m], marker=old.MARKERS[m],
        label=old.LABELS[m], ms=4) for m in METHODS], loc="upper center", ncol=5, frameon=False,
        bbox_to_anchor=(.51, 1.02), fontsize=7)
    trajectories.tight_layout(rect=(0, 0, 1, .89), w_pad=.8)
    ratios.tight_layout(rect=(0, 0, 1, .92), w_pad=.7)
    validate_originals(endpoints, effects, target_rows)
    output = {"figures/three_architecture_trajectories.pdf": old.pdf_bytes(trajectories),
              "figures/three_architecture_target_ratios.pdf": old.pdf_bytes(ratios),
              "figures/three_architecture_protocol.pdf": protocol_figure()}
    output.update({f"evidence/three_architecture_{name}.csv": old.csv_bytes(rows)
        for name, rows in (("endpoints", endpoints), ("endpoint_effects", effects),
                          ("targets", target_rows), ("history", histories), ("coverage", coverage))})
    output.update(tables(endpoints, target_rows))
    return output


def protocol_figure():
    """Use short labels and the full canvas so text stays inside each box."""
    fig, ax = plt.subplots(figsize=(7.08, 1.35))
    fig.subplots_adjust(left=.01, right=.99, top=.99, bottom=.01)
    ax.set(xlim=(0, 10), ylim=(0, 2))
    ax.axis("off")
    boxes = [(0.05, "Client local SGD\nweighted evidence\n"+r"$p_i\delta_i^r/\eta_r$"),
             (2.68, "Stateful encoder\nleak, threshold\nfull reset"),
             (5.31, "Server aggregate\nsum signed pulses\n"+r"scale by $q_r$"),
             (7.94, "Exact synchronization\naggregate counts\n+ fidelity patch")]
    for i, (left, label) in enumerate(boxes):
        ax.add_patch(FancyBboxPatch((left, .7), 2.0, .85, boxstyle="round,pad=.02",
            facecolor="#fff2e8" if i == 1 else "#edf3f7", edgecolor="#555555", linewidth=.8))
        ax.text(left+1.0, 1.125, label, ha="center", va="center", fontsize=7)
    for left, right, label in ((2.08, 2.64, "local evidence"),
                                (4.71, 5.27, "coded support + signs"),
                                (7.34, 7.9, "lossless downlink")):
        ax.add_patch(FancyArrowPatch((left, 1.125), (right, 1.125), arrowstyle="-|>",
            mutation_scale=10, color="#555555", linewidth=.8))
        ax.text((left+right)/2, 1.72, label, ha="center", fontsize=6.5)
    ax.annotate("Next round: all clients start from the same server model",
        xy=(.55, .3), xytext=(9.45, .3), ha="right", va="center", fontsize=7,
        arrowprops={"arrowstyle": "->", "lw": .8, "color": "#555555"})
    return old.pdf_bytes(fig)


def validate_originals(endpoints, effects, targets):
    # Reconcile every new table entry with the original study summaries. The
    # two-CIFAR manuscript products remain immutable and provide another check.
    for panel in PANELS:
        if panel == "fmnist_mlp":
            root, field, target_file = MLP, "method", "paired_targets.csv"
        else:
            directory, _, _, field, _ = old.PANELS[panel]
            root, target_file = REPO/"experiments/results"/directory, "paired_target_summary.csv"
        for original in old.read(root/"endpoint_summary.csv"):
            row = next(r for r in endpoints if r["panel"] == panel and r["method"] == original[field])
            for metric in ("final_test_accuracy", "final_test_ce", "uplink_bits", "unicast_downlink_bits", "unicast_total_bits", "broadcast_total_bits"):
                for stat in ("mean", "std"):
                    key = metric+"_"+stat
                    assert np.isclose(row[key], float(original[key]), rtol=1e-10, atol=1e-8), (panel, key)
        for original in old.read(root/target_file):
            row = next(r for r in targets if r["panel"] == panel and r["reference"] == original["reference"] and abs(r["target_percent"]-100*float(original["target_accuracy"])) < 1e-8)
            n_field = "common_hits" if panel == "fmnist_mlp" else "n_common_hits"
            assert row["common_hits"] == int(original[n_field])
            for new, prior in (("ratio", "estimate"), ("ratio_ci95_low", "ci95_low"), ("ratio_ci95_high", "ci95_high")):
                assert np.isclose(row[new], float(original[prior]), rtol=1e-9, atol=1e-11), (panel, new)
    for original in old.read(MLP/"analysis_confirmation_effects.csv"):
        if original["metric"] not in ("accuracy_difference_pp", "ce_difference", "unicast_ratio"):
            continue
        row = next(r for r in effects if r["panel"] == "fmnist_mlp" and r["reference"] == original["reference"] and r["metric"] == original["metric"])
        for key in ("estimate", "ci95_low", "ci95_high"):
            assert np.isclose(row[key], float(original[key]), rtol=1e-9, atol=1e-10)
    for name, rebuilt in (("endpoints", endpoints), ("targets", targets), ("endpoint_effects", effects)):
        for original in old.read(PAPER/f"evidence/calibrated_core_{name}.csv"):
            keys = ("panel", "method") if name == "endpoints" else ("panel", "reference", "target_percent") if name == "targets" else ("panel", "reference", "metric")
            row = next(r for r in rebuilt if all(str(r[k]) == original[k] for k in keys))
            for key, value in original.items():
                if key not in keys:
                    assert np.isclose(float(row[key]), float(value), rtol=1e-9, atol=1e-8), (name, key)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    old_count, new_count = check_freeze()
    built = products()
    for name, data in built.items():
        path = PAPER/name
        if args.check:
            assert path.exists() and path.read_bytes() == data, f"Stale three-architecture product: {name}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(f"{'Validated' if args.check else 'Rebuilt'} {len(built)} products; 150 outcomes; 36 target contrasts; {old_count} prior and {new_count} MLP frozen inputs; no training.")


if __name__ == "__main__":
    main()
