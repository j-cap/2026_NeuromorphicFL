Architecture = Literal["mlp", "cnn", "cifar_cnn", "cifar_resnet14"]
Method = Literal["event", "strom", "ef_topk", "sign_ef", "dense", "stc"]


@dataclass(frozen=True)
class FinalBaselineConfig:
    local_steps: int = 5
    local_lr: float = 0.1
    batch_size: int = 32
    regularization: float = 1e-4
    rounds: int = 150
    eval_stride: int = 15
    rho: float = 0.999
    threshold: float = 0.025
    jump0: float = 0.005
    jump_scale: float = 100.0
    jump_exponent: float = 0.1
    topk_fraction: float = 0.025
    strom_threshold: float = 0.005
    init_scale: float = 0.5
    server_gain: float = 1.0
    server_gain_exponent: float = 0.0
    server_gain_scale: float = 100.0
    event_memory: Literal["persistent", "memoryless"] = "persistent"
    event_reset: Literal["full", "subtractive"] = "full"
    stc_upload_fraction: float = 0.01
    stc_download_fraction: float = 0.01


def _architecture_ops(architecture: Architecture):
    if architecture == "mlp":
        return MLP_LAYOUT, initialize_mlp, mlp_loss_and_gradient, mlp_predictive_metrics
    if architecture == "cnn":
        return CNN_LAYOUT, initialize_cnn, cnn_loss_and_gradient, cnn_predictive_metrics
    if architecture == "cifar_cnn":
        return (
            CIFAR_CNN_LAYOUT,
            initialize_cifar_cnn,
            cifar_cnn_loss_and_gradient,
            cifar_cnn_predictive_metrics,
        )
    if architecture == "cifar_resnet14":
        return (
            CIFAR_RESNET14_LAYOUT,
            initialize_resnet14,
            cifar_resnet14_loss_and_gradient,
            cifar_resnet14_predictive_metrics,
        )
    raise ValueError(architecture)


def _local_delta(
    w_server: np.ndarray,
    X: np.ndarray,
    y: np.ndarray,
    *,
    config: FinalBaselineConfig,
    rng: np.random.Generator,
    layout,
    loss_grad,
) -> np.ndarray:
    w_local = w_server.copy()
    n = len(y)
    for _ in range(config.local_steps):
        ids = rng.integers(0, n, size=config.batch_size)
        _, _, gradient = loss_grad(
            w_local,
            X[ids],
            y[ids],
            layout=layout,
            regularization=config.regularization,
            need_gradient=True,
        )
        w_local -= config.local_lr * gradient
    return (w_local - w_server).astype(np.float32, copy=False)


def run_final_baseline(
    *,
    federation: MulticlassFederation,
    architecture: Architecture,
    method: Method,
    config: FinalBaselineConfig,
    seed: int = 70707,
    alignment_audit_stride: int | None = None,
    alignment_client_reference_size: int | None = None,
    alignment_audit_rounds: tuple[int, ...] | None = None,
    record_history: bool = False,
    record_group_activity: bool = False,
    checkpoint: BaselineCheckpoint | None = None,
    checkpoint_stride: int = 60,
    progress_callback: Callable[[dict[str, float | int]], None] | None = None,
) -> dict[str, float | int | str | pd.DataFrame]:
    """Run a FedAvg comparator with explicit bidirectional accounting.

    All methods use identical local SGD. Historical compressed methods expose the
    exact server-side packet stream generated by their uplink. A synchronized client
    can reproduce the new server model by replaying that stream.  Conservative
    unicast accounting charges every client a 32-bit catch-up request per round
    and chooses the cheaper of exact replay and a float32 model checkpoint.

    STC instead communicates a separately compressed server update, with client
    and server error feedback. Its native downlink is charged at actual encoded
    length, without replacing it by replay or checkpoint fallback. The existing
    unicast_hybrid_* result keys hold this native cost for schema compatibility.

    Optional numeric checkpoints preserve the model, all compressor residuals,
    RNG, history and traffic counters. The caller supplies a data/source/runtime
    provenance record; incompatible checkpoints are rejected. Audited runs do
    not support checkpointing. Progress callbacks run after checkpoint writes.
    """
    if alignment_audit_stride is not None and alignment_audit_rounds is not None:
        raise ValueError(
            "choose alignment_audit_stride or alignment_audit_rounds, not both"
        )
    audit_enabled = (
        alignment_audit_stride is not None or alignment_audit_rounds is not None
    )
    if audit_enabled:
        if method != "event":
            raise ValueError("alignment auditing is defined only for method='event'")
    if alignment_audit_stride is not None and alignment_audit_stride <= 0:
        raise ValueError("alignment_audit_stride must be positive")
    if alignment_audit_rounds is not None:
        if not alignment_audit_rounds:
            raise ValueError("alignment_audit_rounds must not be empty")
        if min(alignment_audit_rounds) <= 0 or max(alignment_audit_rounds) > config.rounds:
            raise ValueError("alignment_audit_rounds must lie within the run")
    if alignment_client_reference_size is not None:
        if not audit_enabled:
            raise ValueError(
                "alignment_client_reference_size requires alignment auditing"
            )
        if alignment_client_reference_size <= 0:
            raise ValueError("alignment_client_reference_size must be positive")
    if not np.isfinite(config.server_gain) or config.server_gain <= 0.0:
        raise ValueError("server_gain must be finite and positive")
    if (not np.isfinite(config.server_gain_exponent)
            or config.server_gain_exponent < 0.0
            or not np.isfinite(config.server_gain_scale)
            or config.server_gain_scale <= 0.0):
        raise ValueError("invalid dense server-gain schedule")
    if method != "dense" and config.server_gain_exponent != 0.0:
        raise ValueError("scheduled server gain is defined only for dense FedAvg")
    if config.event_memory not in ("persistent", "memoryless"):
        raise ValueError(f"unsupported event memory: {config.event_memory}")
    if config.event_reset not in ("full", "subtractive"):
        raise ValueError(f"unsupported event reset: {config.event_reset}")
    if record_group_activity and method != "event":
        raise ValueError("group activity is defined only for method='event'")
    if checkpoint_stride <= 0:
        raise ValueError("checkpoint_stride must be positive")
    if checkpoint is not None and (audit_enabled or record_group_activity):
        raise ValueError("checkpointing does not support alignment/group audits")

    layout, initialize, loss_grad, metrics = _architecture_ops(architecture)
    rng = np.random.default_rng(seed)
    n_clients = federation.n_clients
    d = int(layout.dimension)
    address_bits = int(math.ceil(math.log2(d)))
    pulse_bits = address_bits + 1
    topk = max(1, int(round(config.topk_fraction * d)))
    weights = federation.weights.astype(float)
    weights /= np.sum(weights)

    w = initialize(layout=layout, seed=7777, scale=config.init_scale)
    event_state = np.zeros((n_clients, d), dtype=np.float32)
    strom_state = np.zeros((n_clients, d), dtype=np.float32)
    residual = np.zeros((n_clients, d), dtype=np.float32)
    stc_state = (
        STCState.zeros(
            n_clients=n_clients,
            tensor_sizes=tuple(size for _, _, size in layout.groups()),
            upload_fraction=config.stc_upload_fraction,
            download_fraction=config.stc_download_fraction,
        )
        if method == "stc" else None
    )
    stc_downlink_packets: list[int] = []
    stc_downlink_bits = 0

    uplink_payload = 0
    uplink_packetized = 0
    messages = 0
    coordinate_events = 0
    delta_norms: list[float] = []
    history_rows: list[dict[str, float | int]] = []
    alignment_rows: list[dict[str, float | int]] = []
    group_activity_rows: list[dict[str, float | int | str]] = []
    round_replay_packetized: list[int] = []
    activity_groups = (
        layout.activity_groups() if hasattr(layout, "activity_groups")
        else layout.groups()
    )

    evidence_gain = 1.0 / config.local_lr
    alignment_reference_size = (
        sum(
            min(alignment_client_reference_size, len(federation.client_y[client]))
            for client in range(n_clients)
        )
        if alignment_client_reference_size is not None
        else len(federation.y_train_eval)
    )

    checkpoint_identity = {
        "method": method, "architecture": architecture, "config": asdict(config),
        "seed": seed, "n_clients": n_clients, "dimension": d,
        "weights": weights.tolist(), "numpy_version": np.__version__,
    }
    checkpoint_arrays = {
        "model": w, "event_state": event_state,
        "strom_state": strom_state, "residual": residual,
    }
    if stc_state is not None:
        checkpoint_arrays.update({
            "stc_client_residuals": stc_state.client_residuals,
            "stc_server_residual": stc_state.server_residual,
        })
    start_round = 0
    saved = checkpoint.load(checkpoint_identity) if checkpoint is not None else None
    if saved is not None:
        if set(saved["arrays"]) != set(checkpoint_arrays):
            raise ValueError("checkpoint state array names differ")
        for name, target in checkpoint_arrays.items():
            source = saved["arrays"][name]
            if (source.shape != target.shape or source.dtype != target.dtype
                    or not np.all(np.isfinite(source))):
                raise ValueError(f"invalid checkpoint array: {name}")
            target[:] = source
        progress = saved["progress"]
        start_round = int(progress["completed_round"])
        if not 0 <= start_round <= config.rounds:
            raise ValueError("checkpoint round is outside the configured horizon")
        rng.bit_generator.state = progress["rng_state"]
        uplink_payload = int(progress["uplink_payload"])
        uplink_packetized = int(progress["uplink_packetized"])
        messages = int(progress["messages"])
        coordinate_events = int(progress["coordinate_events"])
        delta_norms = progress["delta_norms"]
        history_rows = progress["history_rows"]
        round_replay_packetized = progress["round_replay_packetized"]
        stc_downlink_packets = progress["stc_downlink_packets"]
        stc_downlink_bits = int(progress["stc_downlink_bits"])
        packet_history = stc_downlink_packets if method == "stc" else round_replay_packetized
        if (len(delta_norms) != start_round * n_clients
                or len(packet_history) != start_round):
            raise ValueError("checkpoint counters do not match the saved round")

    for rnd in range(start_round + 1, config.rounds + 1):
        audit_round = bool(
            (
                alignment_audit_stride is not None
                and (
                    rnd == 1
                    or rnd % alignment_audit_stride == 0
                    or rnd == config.rounds
                )
            )
            or (
                alignment_audit_rounds is not None
                and rnd in alignment_audit_rounds
            )
        )
        reference_objective_before = float("nan")
        reference_gradient: np.ndarray | None = None
        local_reference_gradients: list[np.ndarray] | None = None
        audit_w_before: np.ndarray | None = None

        deltas: list[np.ndarray] = []
        for client in range(n_clients):
            delta = _local_delta(
                w,
                federation.client_X[client],
                federation.client_y[client],
                config=config,
                rng=rng,
                layout=layout,
                loss_grad=loss_grad,
            )
            if checkpoint is not None and not np.all(np.isfinite(delta)):
                raise FloatingPointError(f"nonfinite local delta at round {rnd}")
            deltas.append(delta)
            delta_norms.append(float(np.linalg.norm(delta)))

        aggregate = np.zeros(d, dtype=np.float32)
        raw_aggregate = np.zeros(d, dtype=np.int16) if audit_round else None
        audit_client_events: list[tuple[np.ndarray, np.ndarray] | None] | None = (
            [None] * n_clients if audit_round else None
        )
        round_coordinate_events = 0
        descent_mass = 0.0
        harmful_mass = 0.0
        ideal_local_mass = 0.0
        memory_opposition_penalty = 0.0
        local_drift_term = 0.0
        heterogeneity_term = 0.0
        silent_local_mass = 0.0
        replay_this_round = 0

        if method == "event":
            if config.event_memory == "memoryless":
                event_state.fill(0.0)
            else:
                event_state *= config.rho
            jump = config.jump0 * (1.0 + rnd / config.jump_scale) ** (-config.jump_exponent)
            group_events = np.zeros(len(activity_groups), dtype=np.int64)
            group_active_clients = np.zeros(len(activity_groups), dtype=np.int64)
            group_abs_evidence = np.zeros(len(activity_groups), dtype=np.float64)
            for client in range(n_clients):
                event_state[client] += evidence_gain * float(weights[client]) * deltas[client]
                mask = np.abs(event_state[client]) >= config.threshold
                if record_group_activity:
                    for group_index, (_, group_slice, _) in enumerate(activity_groups):
                        group_mask = mask[group_slice]
                        group_count = int(np.sum(group_mask))
                        group_events[group_index] += group_count
                        group_active_clients[group_index] += int(group_count > 0)
                        group_abs_evidence[group_index] += float(
                            np.sum(np.abs(event_state[client, group_slice]))
                        )
                count = int(np.sum(mask))
                if count:
                    signs = np.sign(event_state[client, mask]).astype(np.int8)
                    aggregate[mask] += jump * signs.astype(np.float32)
                    round_coordinate_events += count
                    if audit_round:
                        assert raw_aggregate is not None
                        assert audit_client_events is not None
                        raw_aggregate[mask] += signs.astype(np.int16)
                        audit_client_events[client] = (
                            np.flatnonzero(mask),
                            signs.copy(),
                        )
                elif audit_round:
                    assert audit_client_events is not None
                    audit_client_events[client] = (
                        np.empty(0, dtype=np.int64),
                        np.empty(0, dtype=np.int8),
                    )
                if count:
                    if config.event_reset == "full":
                        event_state[client, mask] = 0.0
                    else:
                        event_state[client, mask] -= (
                            config.threshold * signs.astype(np.float32)
                        )
                    bits = count * pulse_bits
                    packet = bits + 64
                    uplink_payload += bits
                    uplink_packetized += packet
                    replay_this_round += packet
                    messages += 1
                    coordinate_events += count
            if record_group_activity:
                for group_index, (group_name, _, group_size) in enumerate(activity_groups):
                    group_activity_rows.append({
                        "round": rnd,
                        "group": group_name,
                        "parameter_count": group_size,
                        "coordinate_events": int(group_events[group_index]),
                        "active_clients": int(group_active_clients[group_index]),
                        "firing_fraction": float(
                            group_events[group_index] / (n_clients * group_size)
                        ),
                        "mean_abs_pre_reset_evidence": float(
                            group_abs_evidence[group_index] / (n_clients * group_size)
                        ),
                    })

        elif method == "strom":
            tau = float(config.strom_threshold)
            for client in range(n_clients):
                strom_state[client] += evidence_gain * float(weights[client]) * deltas[client]
                mask = np.abs(strom_state[client]) >= tau
                count = int(np.sum(mask))
                if count:
                    signs = np.sign(strom_state[client, mask]).astype(np.int8)
                    aggregate[mask] += tau * signs.astype(np.float32)
                    # Residual-conserving Strom pulse: subtract the transmitted quantum.
                    strom_state[client, mask] -= tau * signs.astype(np.float32)
                    bits = count * pulse_bits
                    packet = bits + 64
                    uplink_payload += bits
                    uplink_packetized += packet
                    replay_this_round += packet
                    messages += 1
                    coordinate_events += count

        elif method == "ef_topk":
            for client in range(n_clients):
                residual[client] += float(weights[client]) * deltas[client]
                ids = np.argpartition(np.abs(residual[client]), -topk)[-topk:]
                values = residual[client, ids].copy()
                aggregate[ids] += values
                residual[client, ids] = 0.0
                bits = topk * (32 + address_bits)
                packet = bits + 64
                uplink_payload += bits
                uplink_packetized += packet
                replay_this_round += packet
                messages += 1

        elif method == "sign_ef":
            for client in range(n_clients):
                residual[client] += float(weights[client]) * deltas[client]
                scale = float(np.mean(np.abs(residual[client])))
                if scale > 0:
                    compressed = (scale * np.sign(residual[client])).astype(np.float32)
                    aggregate += compressed
                    residual[client] -= compressed
                bits = d + 32
                packet = bits + 64
                uplink_payload += bits
                uplink_packetized += packet
                replay_this_round += packet
                messages += 1

        elif method == "stc":
            assert stc_state is not None
            communicated = stc_state.step(
                deltas, weights, server_gain=float(config.server_gain),
            )
            aggregate = communicated.server_update
            for packet in communicated.uplink:
                uplink_payload += packet.payload_bits
                uplink_packetized += packet.wire_bits
                coordinate_events += packet.nonzeros
                messages += 1
            stc_downlink_packets.append(communicated.downlink.wire_bits)
            stc_downlink_bits += communicated.downlink.wire_bits

        elif method == "dense":
            for client in range(n_clients):
                aggregate += float(weights[client]) * deltas[client]
                bits = 32 * d
                packet = bits + 64
                uplink_payload += bits
                uplink_packetized += packet
                replay_this_round += packet
                messages += 1
        else:
            raise ValueError(method)

        # A deterministic server gain is part of the optimizer, not the
        # communication payload.  The frozen campaigns use one.  P8 exposes
        # this standard degree of freedom for a development-only dense-FedAvg
        # fairness audit.
        # Zero exponent exactly preserves all historical baseline trajectories.
        gain = float(config.server_gain) * (
            1.0 + rnd / float(config.server_gain_scale)
        ) ** (-float(config.server_gain_exponent))
        if method != "stc":
            # STC applies the gain before server error feedback, so that its
            # retained server residual has the units of the applied update.
            aggregate *= gain
        if audit_round:
            audit_w_before = w.copy()
        w += aggregate
        if method != "stc":
            round_replay_packetized.append(int(replay_this_round))

        if audit_round:
            assert raw_aggregate is not None
            assert audit_client_events is not None
            assert audit_w_before is not None
            if alignment_client_reference_size is None:
                (
                    reference_objective_before,
                    _,
                    reference_gradient,
                ) = loss_grad(
                    audit_w_before,
                    federation.X_train_eval,
                    federation.y_train_eval,
                    layout=layout,
                    regularization=config.regularization,
                    need_gradient=True,
                )
            else:
                reference_objective_before = 0.0
                reference_gradient = np.zeros(d, dtype=np.float64)
                local_reference_gradients = []
                for client in range(n_clients):
                    n_reference = min(
                        alignment_client_reference_size,
                        len(federation.client_y[client]),
                    )
                    local_objective, _, local_gradient = loss_grad(
                        audit_w_before,
                        federation.client_X[client][:n_reference],
                        federation.client_y[client][:n_reference],
                        layout=layout,
                        regularization=config.regularization,
                        need_gradient=True,
                    )
                    local_reference_gradients.append(
                        local_gradient.astype(np.float64, copy=False)
                    )
                    reference_objective_before += (
                        float(weights[client]) * float(local_objective)
                    )
                    reference_gradient += float(weights[client]) * local_gradient

            for client, event in enumerate(audit_client_events):
                assert event is not None
                ids, signs = event
                local_proxy = (
                    deltas[client].astype(np.float64, copy=False)
                    / (config.local_lr * config.local_steps)
                )
                proxy_on_events = local_proxy[ids]
                silent_local_mass += float(
                    np.sum(np.abs(local_proxy)) - np.sum(np.abs(proxy_on_events))
                )
                if len(ids) == 0:
                    continue
                signs_float = signs.astype(np.float64, copy=False)
                gradient_on_events = reference_gradient[ids]
                signed_products = gradient_on_events * signs_float
                absolute_gradient = np.abs(gradient_on_events)
                descent_mass += float(
                    np.sum(absolute_gradient[signed_products < 0.0])
                )
                harmful_mass += float(
                    np.sum(absolute_gradient[signed_products > 0.0])
                )
                if local_reference_gradients is not None:
                    local_gradient_on_events = local_reference_gradients[client][ids]
                    ideal_local_mass += float(np.sum(np.abs(proxy_on_events)))
                    memory_opposition_penalty += float(
                        2.0
                        * np.sum(
                            np.abs(
                                proxy_on_events[
                                    proxy_on_events * signs_float < 0.0
                                ]
                            )
                        )
                    )
                    local_drift_term += float(
                        np.sum(
                            (-local_gradient_on_events - proxy_on_events)
                            * signs_float
                        )
                    )
                    heterogeneity_term += float(
                        np.sum(
                            (local_gradient_on_events - gradient_on_events)
                            * signs_float
                        )
                    )

            assert reference_gradient is not None
            if alignment_client_reference_size is None:
                reference_objective_after, _ = loss_grad(
                    w,
                    federation.X_train_eval,
                    federation.y_train_eval,
                    layout=layout,
                    regularization=config.regularization,
                    need_gradient=False,
                )
            else:
                reference_objective_after = 0.0
                for client in range(n_clients):
                    n_reference = min(
                        alignment_client_reference_size,
                        len(federation.client_y[client]),
                    )
                    local_objective_after, _ = loss_grad(
                        w,
                        federation.client_X[client][:n_reference],
                        federation.client_y[client][:n_reference],
                        layout=layout,
                        regularization=config.regularization,
                        need_gradient=False,
                    )
                    reference_objective_after += (
                        float(weights[client]) * float(local_objective_after)
                    )
            gradient_sq_norm = float(reference_gradient @ reference_gradient)
            raw_aggregate_float = raw_aggregate.astype(np.float64)
            aggregate_energy = float(
                raw_aggregate_float @ raw_aggregate_float
            )
            aggregate_l1 = float(np.sum(np.abs(raw_aggregate)))
            net_alignment = float(descent_mass - harmful_mass)
            inner_product_alignment = float(
                -reference_gradient @ raw_aggregate.astype(np.float32)
            )
            objective_change = float(
                reference_objective_after - reference_objective_before
            )
            effective_jump = float(jump) * float(config.server_gain)
            first_order_change = float(-effective_jump * net_alignment)
            alignment_row: dict[str, float | int] = {
                    "round": rnd,
                    "jump": effective_jump,
                    "reference_size": int(alignment_reference_size),
                    "reference_objective_before": float(reference_objective_before),
                    "reference_objective_after": float(reference_objective_after),
                    "objective_change": objective_change,
                    "gradient_sq_norm": gradient_sq_norm,
                    "gradient_norm": float(np.sqrt(gradient_sq_norm)),
                    "coordinate_events": int(round_coordinate_events),
                    "aggregate_nonzeros": int(np.count_nonzero(raw_aggregate)),
                    "aggregate_l1": aggregate_l1,
                    "aggregate_energy": aggregate_energy,
                    "event_energy_ratio": (
                        aggregate_energy / (n_clients * round_coordinate_events)
                        if round_coordinate_events
                        else 0.0
                    ),
                    "cancellation_fraction": (
                        1.0 - aggregate_l1 / round_coordinate_events
                        if round_coordinate_events
                        else 0.0
                    ),
                    "descent_mass": descent_mass,
                    "harmful_mass": harmful_mass,
                    "net_alignment": net_alignment,
                    "inner_product_alignment": inner_product_alignment,
                    "alignment_identity_error": float(
                        abs(net_alignment - inner_product_alignment)
                    ),
                    "alignment_ratio": (
                        net_alignment / gradient_sq_norm
                        if gradient_sq_norm > 0.0
                        else float("nan")
                    ),
                    "harmful_share": (
                        harmful_mass / (descent_mass + harmful_mass)
                        if descent_mass + harmful_mass > 0.0
                        else float("nan")
                    ),
                    "first_order_change": first_order_change,
                    "curvature_remainder": objective_change - first_order_change,
                    "objective_decreased": int(objective_change < 0.0),
                    "net_alignment_positive": int(net_alignment > 0.0),
                    "update_reconstruction_error": float(
                        np.linalg.norm(
                            aggregate
                            - effective_jump * raw_aggregate.astype(np.float32)
                        )
                    ),
                }
            if local_reference_gradients is not None:
                decomposition_alignment = (
                    ideal_local_mass
                    - memory_opposition_penalty
                    + local_drift_term
                    + heterogeneity_term
                )
                alignment_row.update(
                    {
                        "ideal_local_mass": ideal_local_mass,
                        "memory_opposition_penalty": memory_opposition_penalty,
                        "local_drift_term": local_drift_term,
                        "heterogeneity_term": heterogeneity_term,
                        "silent_local_mass": silent_local_mass,
                        "event_local_mass_fraction": (
                            ideal_local_mass
                            / (ideal_local_mass + silent_local_mass)
                            if ideal_local_mass + silent_local_mass > 0.0
                            else float("nan")
                        ),
                        "decomposition_alignment": decomposition_alignment,
                        "decomposition_identity_error": abs(
                            net_alignment - decomposition_alignment
                        ),
                    }
                )
            alignment_rows.append(alignment_row)

        if rnd == 1 or rnd % config.eval_stride == 0 or rnd == config.rounds:
            train_obj, train_ce, _, _, _, _ = metrics(
                w,
                federation.X_train_eval,
                federation.y_train_eval,
                layout=layout,
                regularization=config.regularization,
            )
            _, test_ce, test_acc, macro_acc, worst_acc, _ = metrics(
                w,
                federation.X_test,
                federation.y_test,
                layout=layout,
                regularization=config.regularization,
            )
            history_rows.append(
                {
                    "round": rnd,
                    "train_objective": train_obj,
                    "train_ce": train_ce,
                    "test_ce": test_ce,
                    "test_accuracy": test_acc,
                    "macro_accuracy": macro_acc,
                    "worst_class_accuracy": worst_acc,
                    "uplink_packetized_bits": uplink_packetized,
                }
            )
            if method == "stc":
                initial_packet = 32 * d + 64
                history_rows[-1].update({
                    "stc_downlink_packetized_bits": stc_downlink_bits,
                    "broadcast_total_bits": (
                        uplink_packetized + initial_packet + stc_downlink_bits
                    ),
                    "unicast_total_bits": (
                        uplink_packetized + n_clients * (
                            initial_packet + 32 * rnd + stc_downlink_bits
                        )
                    ),
                })

        if checkpoint is not None and (
            rnd % checkpoint_stride == 0 or rnd == config.rounds
        ):
            checkpoint.save(checkpoint_identity, checkpoint_arrays, {
                "completed_round": rnd, "rng_state": rng.bit_generator.state,
                "uplink_payload": uplink_payload,
                "uplink_packetized": uplink_packetized,
                "messages": messages, "coordinate_events": coordinate_events,
                "delta_norms": delta_norms, "history_rows": history_rows,
                "round_replay_packetized": round_replay_packetized,
                "stc_downlink_packets": stc_downlink_packets,
                "stc_downlink_bits": stc_downlink_bits,
            })
        if progress_callback is not None and (
            rnd == 1 or rnd % config.eval_stride == 0 or rnd == config.rounds
        ):
            progress_callback({
                "round": rnd, "rounds": config.rounds,
                "train_objective": float(history_rows[-1]["train_objective"]),
                "uplink_packetized_bits": uplink_packetized,
            })

    history = pd.DataFrame(history_rows)
    train_obj, train_ce, _, _, _, _ = metrics(
        w,
        federation.X_train_eval,
        federation.y_train_eval,
        layout=layout,
        regularization=config.regularization,
    )
    _, test_ce, test_acc, macro_acc, worst_acc, per_class = metrics(
        w,
        federation.X_test,
        federation.y_test,
        layout=layout,
        regularization=config.regularization,
    )

    # End-to-end synchronization accounting.
    checkpoint_payload = 32 * d
    checkpoint_packet = checkpoint_payload + 64
    request_bits = 32

    # Initial model synchronization is charged explicitly.
    broadcast_down = checkpoint_packet
    unicast_down = n_clients * checkpoint_packet
    replay_rounds = 0
    checkpoint_rounds = 0
    for replay_bits in round_replay_packetized:
        if replay_bits <= checkpoint_packet:
            replay_rounds += 1
        else:
            checkpoint_rounds += 1
        broadcast_down += min(replay_bits, checkpoint_packet)
        unicast_down += n_clients * (request_bits + min(replay_bits, checkpoint_packet))
    if method == "stc":
        # This is the native STC server stream, never the client-upload stream.
        broadcast_down += stc_downlink_bits
        unicast_down += n_clients * (
            config.rounds * request_bits + stc_downlink_bits
        )

    result: dict[str, float | int | str] = {
        "architecture": architecture,
        "method": method,
        "dimension": d,
        "rounds": config.rounds,
        "local_steps": config.local_steps,
        "local_lr": config.local_lr,
        "final_train_objective": float(train_obj),
        "final_train_ce": float(train_ce),
        "final_test_ce": float(test_ce),
        "final_test_accuracy": float(test_acc),
        "final_macro_accuracy": float(macro_acc),
        "final_worst_class_accuracy": float(worst_acc),
        "whole_train_objective": float(history["train_objective"].mean()),
        "uplink_payload_bits": int(uplink_payload),
        "uplink_packetized_bits": int(uplink_packetized),
        "broadcast_downlink_bits": int(broadcast_down),
        "unicast_hybrid_downlink_bits": int(unicast_down),
        "broadcast_total_bits": int(uplink_packetized + broadcast_down),
        "unicast_hybrid_total_bits": int(uplink_packetized + unicast_down),
        "messages": int(messages),
        "coordinate_events": int(coordinate_events),
        "events_per_message": float(coordinate_events / messages) if messages else 0.0,
        "mean_delta_norm": float(np.mean(delta_norms)),
        "replay_rounds": int(replay_rounds),
        "checkpoint_rounds": int(checkpoint_rounds),
        "rho": float(config.rho),
        "threshold": float(config.threshold),
        "jump0": float(config.jump0),
        "jump_exponent": float(config.jump_exponent),
        "topk_fraction": float(config.topk_fraction),
        "strom_threshold": float(config.strom_threshold),
        "init_scale": float(config.init_scale),
        "server_gain": float(config.server_gain),
        "server_gain_exponent": float(config.server_gain_exponent),
        "server_gain_scale": float(config.server_gain_scale),
        "event_memory": config.event_memory,
        "event_reset": config.event_reset,
    }
    if method == "stc":
        assert stc_state is not None
        result.update({
            "stc_protocol": STC_PROTOCOL,
            "stc_grouping": "parameter_tensor",
            "stc_upload_fraction": float(config.stc_upload_fraction),
            "stc_download_fraction": float(config.stc_download_fraction),
            "stc_downlink_packetized_bits": stc_downlink_bits,
            "stc_downlink_messages": len(stc_downlink_packets),
            "downlink_protocol": "stc_compressed_server_update",
            "unicast_total_bits": int(uplink_packetized + unicast_down),
            "stc_client_residual_norm": float(np.linalg.norm(stc_state.client_residuals)),
            "stc_server_residual_norm": float(np.linalg.norm(stc_state.server_residual)),
        })
    for cls, acc in enumerate(per_class):
        result[f"class_{cls}_accuracy"] = float(acc)
    if audit_enabled:
        if alignment_audit_stride is not None:
            result["alignment_audit_stride"] = int(alignment_audit_stride)
        if alignment_audit_rounds is not None:
            result["alignment_audit_rounds"] = ",".join(
                str(round_index) for round_index in alignment_audit_rounds
            )
        result["alignment_reference_size"] = int(alignment_reference_size)
        if alignment_client_reference_size is not None:
            result["alignment_client_reference_size"] = int(
                alignment_client_reference_size
            )
        result["alignment_audit"] = pd.DataFrame(alignment_rows)
    if record_history:
        result["history"] = history
    if record_group_activity:
        result["group_activity"] = pd.DataFrame(group_activity_rows)
    return result
